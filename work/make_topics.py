import re, json
def parse(path):
    txt = open(path, encoding='utf-8').read()
    lines = [l.strip() for l in txt.split('\n')]
    skip = ('ТЕМЫ ', 'СПЕЦИАЛЬНОГО', 'СПЕЦПРОЕКТА', '«ТВОЙ ХОД', 'Х ДЕБАТТЛ', 'И МЕЖРЕГИОНАЛЬНОГО')
    items, cur = [], None
    for l in lines:
        if not l or l.startswith(skip) or l == 'Х ДЕБАТТЛ» 2026': continue
        m = re.match(r'^(\d+)\.\s+(.*)$', l)
        if m: cur = [int(m.group(1)), m.group(2)]; items.append(cur)
        else: cur[1] += ' ' + l
    return items
